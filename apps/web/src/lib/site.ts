import { z } from "zod";

/** [lon, lat] in WGS84 degrees. */
export const LonLat = z.tuple([z.number(), z.number()]);

export const Proposal = z.object({
  id: z.string(),
  name: z.string(),
  summary: z.string().optional(),
  /** Closed ring, first point not repeated. */
  footprint: z.array(LonLat).min(3),
  /** Metres above the base elevation. */
  height: z.number().positive(),
  /** Metres above the ellipsoid. Defaults to the site base elevation. */
  baseElevation: z.number().optional(),
  /** CSS colour. */
  color: z.string().optional(),
  /**
   * Massing as one or more extruded volumes, each from the ground. Defaults to the footprint
   * extruded by `height`. `holes` cut courtyards.
   */
  volumes: z
    .array(
      z.object({
        footprint: z.array(LonLat).min(3),
        holes: z.array(z.array(LonLat).min(3)).optional(),
        height: z.number().positive(),
      }),
    )
    .optional(),
  // Masterplan plot metadata (all optional, shown in the plot card when present).
  barrio: z.string().optional(),
  manzana: z.string().optional(),
  stage: z.enum(["propuesta", "formulación", "adoptado", "construcción"]).optional(),
  homes: z.number().optional(),
  /** 0–1 share of social housing (VIS/VIP). */
  visShare: z.number().optional(),
  uses: z.string().optional(),
  floors: z.number().optional(),
});
export type Proposal = z.infer<typeof Proposal>;

/** Existing buildings as a 3D Tiles tileset generated by packages/catastro. */
export const Buildings = z.object({
  /** Path to a tileset.json served from /public, or a Cesium ion asset id. */
  tileset: z.union([z.string(), z.number()]),
  attribution: z.string().optional(),
});

export const Site = z.object({
  slug: z.string(),
  /** "options": compare alternatives for one lot. "masterplan": many plots in a plan area. */
  kind: z.enum(["options", "masterplan"]).default("options"),
  /** Who runs the real project, shown as context. */
  promoter: z.string().optional(),
  /** Legal act or reference for the real project. */
  reference: z.string().optional(),
  /** Headline figures for the plan, shown in the site card. */
  facts: z.array(z.tuple([z.string(), z.string()])).optional(),
  name: z.string(),
  city: z.string(),
  description: z.string().optional(),
  /** Metres above the ellipsoid at the site. Bogotá sits at ~2,600 m. */
  baseElevation: z.number(),
  /** Camera home: [lon, lat, height] and heading/pitch in degrees. */
  home: z.object({
    position: z.tuple([z.number(), z.number(), z.number()]),
    heading: z.number(),
    pitch: z.number(),
  }),
  /** Where the real-world context comes from. */
  context: z.object({
    /** Use Google Photorealistic 3D Tiles when the city has coverage. */
    google3d: z.boolean().default(false),
    /** City-published 3D buildings (Bogotá: IDECA Volumetría 2025, LiDAR) as 3D Tiles. */
    buildings: Buildings.optional(),
    /** Cesium ion terrain asset id built from the city's own DTM. Defaults to World Terrain. */
    terrain: z.number().optional(),
    /** Street trees as 3D Tiles (Bogotá: Jardín Botánico census). */
    trees: z.object({ tileset: z.string(), attribution: z.string().optional() }).optional(),
    /** Ground overlays baked to GeoJSON by packages/catastro/src/overlays.ts. */
    overlays: z
      .object({
        parks: z.string().optional(),
        lots: z.string().optional(),
        /** Project area outline, drawn as a wide yellow band on the ground. */
        boundary: z.string().optional(),
        water: z.string().optional(),
        /** Metro stations (polygons) and alignments (lines), with `line` and `kind` properties. */
        metro: z.string().optional(),
      })
      .optional(),
  }),
  proposals: z.array(Proposal).min(1),
});
export type Site = z.infer<typeof Site>;

export async function loadSite(slug: string): Promise<Site> {
  const mod = await import(`../../sites/${slug}.json`);
  return Site.parse(mod.default);
}
